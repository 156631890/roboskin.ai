/** @param {ExperimentEvidence[]} entries */
export function buildExperimentCsv(entries) {
  const fields = ['id', 'study', 'task', 'version', 'setup', 'metric', 'result', 'comparator',
    'sample', 'interpretation', 'limitation', 'access', 'sourceUrl', 'sourceLocation', 'reviewed'];
  const rows = entries.map((entry) => [...fields.map((field) => entry[field]),
    `https://roboskin.ai${entry.reviewUrl}`, `https://roboskin.ai/benchmarks#result-${entry.id}`]);
  return '\uFEFF' + [[...fields, 'reviewUrl', 'recordUrl'], ...rows]
    .map((row) => row.map(csvCell).join(',')).join('\r\n') + '\r\n';
}
